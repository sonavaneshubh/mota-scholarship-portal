const documentNames = [
  'Aadhaar Card',
  'Domicile Certificate',
  'Income Certificate',
  'ST / PVTG Certificate',
  '12th Marksheet',
  'Previous / Last Year Marksheet',
  'Passport-size Photograph',
];

function createDocuments(
  applicationId: string,
  status: AdminDocumentStatus,
  updatedAt: string,
  rejectionReason?: string,
): AdminDocument[] {
  return documentNames.map((name, index) => {
    const isException = status !== 'Verified' && index === 1;
    const documentStatus: AdminDocumentStatus = isException ? status : 'Verified';

    return {
      id: `${applicationId.toLowerCase()}-doc-${index + 1}`,
      applicationId,
      name,
      fileName: `${applicationId.toLowerCase()}-${name.toLowerCase().replace(/ /g, '-')}.pdf`,
      status: documentStatus,
      uploadedAt: '18 Aug 2026',
      updatedAt,
      required: true,
      ...(isException && rejectionReason ? { rejectionReason } : {}),
    };
  });
}

function application(
  data: Omit<AdminApplication, 'documents' | 'documentStatus'>,
  documentStatus: AdminDocumentStatus,
): AdminApplication {
  const documentLabel: AdminApplication['documentStatus'] =
    documentStatus === 'Rejected' || documentStatus === 'Re-upload Requested'
      ? 'Documents Required'
      : documentStatus === 'Under Verification' || documentStatus === 'Uploaded'
        ? 'Pending Verification'
        : 'Complete';

  return {
    ...data,
    documentStatus: documentLabel,
    documents: createDocuments(data.id, documentStatus, data.lastActivity, data.rejectionReason),
  };
}

