-- -----------------------------------------------------------------------------
-- Column contract.
--
-- The live database already has most of these columns, but the completeness
-- engine in 20260926090100 and the profile services read every one of them. Any
-- column that is merely ASSUMED to exist turns a missing column into a hard
-- "column does not exist" failure inside a plpgsql function, where the error
-- message points at the function rather than at the gap. So the full set the
-- engine touches is asserted here.
--
-- `if not exists` makes this a no-op wherever the column is already present,
-- whatever its existing type. Nothing here can change a live column.
-- -----------------------------------------------------------------------------
