-- =============================================================================
-- Applicant profile — structural extensions to the EXISTING profile tables.
--
-- The live database already contains these tables with a partial column set.
-- This migration is strictly ADDITIVE: it never drops or renames a column, so
-- existing rows, existing queries and the existing admin/scheme tables keep
-- working. Every statement is idempotent and can be re-run safely.
--
-- Canonical existing columns that this migration REUSES instead of duplicating:
--   applicant_profiles.mobile_number      (not "mobile")
--   applicant_profiles.aadhaar_last4      (masked display source)
--   income_details.annual_income          (not "family_annual_income")
--   current_courses.mode_of_study         (not "mode")
--   current_courses.institution_name      (free text) + new institution_id
--   current_courses.university_name       (free text) + new board_university
--   bank_details.account_number           (legacy plaintext — locked to NULL)
--   bank_details.ifsc_code                (not "ifsc")
-- =============================================================================

-- -----------------------------------------------------------------------------
-- profiles: the repo migration 20260925120000 was never applied to this project.
-- Re-assert it idempotently so the auth/role plumbing the frontend depends on
-- (profiles.role, current_profile_role) actually exists.
-- -----------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  email text,
  role text not null default 'applicant' check (role in ('applicant', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

create or replace function public.set_profiles_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_profiles_updated_at on public.profiles;
create trigger set_profiles_updated_at
before update on public.profiles
for each row
execute function public.set_profiles_updated_at();

